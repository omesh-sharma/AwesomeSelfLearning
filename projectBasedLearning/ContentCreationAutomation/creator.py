#!/usr/bin/env python3
"""
auto_short_pipeline.py
Minimal automated pipeline:
1) (optional) script generation via OpenAI
2) TTS via gTTS
3) Download a Pexels video clip
4) Combine clip + audio into a vertical Short using ffmpeg
5) (optional) Upload to YouTube (OAuth2 + YouTube Data API)

Before running:
- Install ffmpeg and ensure `ffmpeg` is in PATH.
- pip install -r requirements.txt (see below)
- Create a Pexels API key and set PEXELS_API_KEY in environment or config below.
- (Optional) Create OpenAI API key and set OPENAI_API_KEY if you want better scripts.
- (Optional) For YouTube upload: create OAuth2 credentials and save client_secrets.json, see instructions below.

This script is intentionally simple and synchronous so you can run it locally and inspect outputs.
"""

