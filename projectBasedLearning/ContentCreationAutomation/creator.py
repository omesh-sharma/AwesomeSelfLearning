def generate_short_script(topic: str, max_seconds: int = 40) -> str:
    """
    Generate a ~30 second short script. If OPENAI_API_KEY is set and openai package is available,
    uses OpenAI's API. Otherwise, falls back to a lightweight built-in template generator.
    """
    if OPENAI_API_KEY and openai:
        try:
            openai.api_key = OPENAI_API_KEY
            logger.info("Generating script via OpenAI...")
            prompt = (
                f"Write a short, punchy YouTube Short script about: {topic}\n"
                f"Requirements: <= {max_seconds} seconds spoken (approx 60-90 words), "
                "hook in first 3 words, simple sentence structure, call-to-action at end."
            )
            # using ChatCompletion (gpt-3.5) style for portability
            completion = openai.ChatCompletion.create(
                model="gpt-4o-mini" if "gpt-4o-mini" in openai.Model.list().__str__() else "gpt-4o-mini",
                messages=[{"role":"user","content":prompt}],
                max_tokens=180,
                temperature=0.7,
            )
            text = completion["choices"][0]["message"]["content"].strip()
            logger.info("Script generated by OpenAI.")
            return text
        except Exception as e:
            logger.warning("OpenAI generation failed, falling back to local generator. Error: %s", e)

    # fallback
    logger.info("Using fallback local script generator.")
    template = (
        f"Here's a quick tip about {topic}. "
        "First, remember this main idea: focus on one small step. "
        "Next, try this action right now: pause, open your notes, and write down one thing you can do in 10 minutes. "
        "If you want more tips like this, follow for daily shorts!"
    )
    return template


def tts_save_gtts(text: str, out_mp3: Path, lang: str = "en") -> None:
    """Convert text -> mp3 using gTTS (free)."""
    logger.info("Creating TTS audio (gTTS)...")
    try:
        tts = gTTS(text=text, lang=lang)
        tts.save(str(out_mp3))
        logger.info("Saved TTS to %s", out_mp3)
    except Exception as e:
        logger.exception("gTTS failed: %s", e)
        raise


def search_pexels_video(query: str, per_page: int = 5) -> Optional[dict]:
    """Search Pexels videos and return the best-fit video metadata (or None)."""
    if not PEXELS_API_KEY:
        raise RuntimeError("PEXELS_API_KEY not set. Get a free key at https://www.pexels.com/api/")
    headers = {"Authorization": PEXELS_API_KEY}
    params = {"query": query, "per_page": per_page}
    url = "https://api.pexels.com/videos/search"
    logger.info("Searching Pexels for query: %s", query)
    r = requests.get(url, headers=headers, params=params, timeout=20)
    r.raise_for_status()
    data = r.json()
    videos = data.get("videos", [])
    if not videos:
        logger.warning("No videos found for query: %s", query)
        return None
    # Pick video with highest duration <= 60s if possible, otherwise first
    for v in videos:
        if v.get("duration", 999) <= 60:
            logger.info("Selected video id=%s duration=%s", v.get("id"), v.get("duration"))
            return v
    logger.info("Falling back to first video.")
    return videos[0]


def download_pexels_video(video_meta: dict, dest_path: Path) -> Path:
    """Download the first available video file (highest quality) from Pexels video metadata."""
    video_files = video_meta.get("video_files", [])
    if not video_files:
        raise RuntimeError("Pexels video metadata contains no video_files.")
    # Prefer mp4 & bigger width
    video_files_sorted = sorted(video_files, key=lambda f: (f.get("width", 0), f.get("fps", 0)), reverse=True)
    best = video_files_sorted[0]
    video_url = best.get("link")
    if not video_url:
        raise RuntimeError("No downloadable link found in video file metadata.")
    logger.info("Downloading Pexels video from %s ...", video_url)
    with requests.get(video_url, stream=True, timeout=60) as r:
        r.raise_for_status()
        with open(dest_path, "wb") as f:
            shutil.copyfileobj(r.raw, f)
    logger.info("Downloaded video to %s", dest_path)
    return dest_path


def make_vertical_short(input_video: Path, input_audio: Path, output_video: Path, target_width: int = 1080, target_height: int = 1920) -> None:
    """
    Use ffmpeg to:
    - scale input video to target width (maintain aspect) and pad to vertical (1080x1920)
    - add audio and encode to mp4
    Requires ffmpeg in PATH.
    """
    logger.info("Creating vertical short via ffmpeg...")
    if not shutil.which("ffmpeg"):
        raise RuntimeError("ffmpeg not found in PATH. Install ffmpeg and try again.")
    # build ffmpeg command
    # scale to width, then pad vertically to target size centered
    cmd = [
        "ffmpeg", "-y",
        "-i", str(input_video),
        "-i", str(input_audio),
        "-filter_complex",
        f"[0:v]scale={target_width}:-2,setsar=1,pad={target_width}:{target_height}:(ow-iw)/2:(oh-ih)/2:black[v]",
        "-map", "[v]",
        "-map", "1:a",
        "-c:v", "libx264", "-pix_fmt", "yuv420p",
        "-c:a", "aac", "-b:a", "128k",
        "-shortest",
        str(output_video)
    ]
    logger.debug("ffmpeg command: %s", " ".join(cmd))
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        logger.error("ffmpeg failed: %s\nSTDOUT: %s\nSTDERR: %s", proc.returncode, proc.stdout, proc.stderr)
        raise RuntimeError("ffmpeg failed; see log")
    logger.info("Short created at %s", output_video)


