YOUTUBE_SCOPES = ["https://www.googleapis.com/auth/youtube.upload"]

def build_youtube_service(client_secrets_file: str = CLIENT_SECRETS_FILE, token_file: str = YOUTUBE_TOKEN_FILE):
    if not InstalledAppFlow:
        raise RuntimeError("Google client libraries not installed. Install google-auth-oauthlib and google-api-python-client.")
    creds = None
    if os.path.exists(token_file):
        with open(token_file, "rb") as f:
            creds = pickle.load(f)
    # If no (valid) creds, run OAuth flow
    if not creds or not getattr(creds, "valid", False):
        if creds and getattr(creds, "expired", False) and getattr(creds, "refresh_token", None):
            try:
                creds.refresh(Request())
            except Exception as e:
                logger.warning("Failed to refresh credentials: %s", e)
                creds = None
        if not creds:
            if not os.path.exists(client_secrets_file):
                raise RuntimeError(f"Client secrets file not found at '{client_secrets_file}'. Create OAuth 2.0 credentials and download client_secrets.json.")
            flow = InstalledAppFlow.from_client_secrets_file(client_secrets_file, YOUTUBE_SCOPES)
            creds = flow.run_console()
            # Save token
            with open(token_file, "wb") as f:
                pickle.dump(creds, f)
    service = build("youtube", "v3", credentials=creds)
    return service


def upload_to_youtube(video_file: Path, title: str, description: str, tags: Optional[list[str]] = None, privacy_status: str = "public"):
    """Upload via YouTube Data API (requires OAuth setup)."""
    logger.info("Uploading to YouTube: %s", video_file)
    service = build_youtube_service()
    body = {
        "snippet": {
            "title": title,
            "description": description,
            "tags": tags or []
        },
        "status": {
            "privacyStatus": privacy_status
        }
    }
    media = MediaFileUpload(str(video_file), chunksize=-1, resumable=True, mimetype="video/*")
    request = service.videos().insert(part="snippet,status", body=body, media_body=media)
    response = None
    while response is None:
        try:
            status, response = request.next_chunk()
            if status:
                logger.info("Upload progress: %.2f%%", status.progress() * 100)
        except Exception as e:
            logger.exception("Upload failed: %s", e)
            raise
    logger.info("Upload successful. Video id: %s", response.get("id"))
    return response.get("id")


# ----------------------------
# Main flow
# ----------------------------
def run_pipeline(topic: str, do_upload: bool = False, output_name_prefix: Optional[str] = None):
    output_name_prefix = output_name_prefix or topic.replace(" ", "_")[:30]
    tmpdir = Path(tempfile.mkdtemp(prefix="short_pipeline_"))
    try:
        # 1) Generate script
        script_text = generate_short_script(topic)
        logger.info("Script: %s", script_text)

        # 2) TTS -> mp3
        audio_file = tmpdir / f"{output_name_prefix}.mp3"
        tts_save_gtts(script_text, audio_file)

        # 3) Find and download a Pexels clip
        video_meta = search_pexels_video(topic)
        if not video_meta:
            raise RuntimeError("No suitable video found on Pexels for topic: " + topic)
        input_video = tmpdir / f"{output_name_prefix}.mp4"
        download_pexels_video(video_meta, input_video)

        # 4) Combine into vertical short
        final_output = OUTPUT_DIR / f"{output_name_prefix}_short.mp4"
        make_vertical_short(input_video, audio_file, final_output)

        # 5) Prepare description with attribution (save license proof)
        desc = f"{topic}\n\nGenerated automatically.\n\nPexels video source: {video_meta.get('url') or video_meta.get('video_files')[0].get('link')}\n"
        # Save local record of metadata and license-like info
        meta_file = OUTPUT_DIR / f"{output_name_prefix}_meta.json"
        with open(meta_file, "w", encoding="utf-8") as f:
            json.dump({"topic": topic, "script": script_text, "pexels_meta": video_meta}, f, indent=2)

        logger.info("Short ready: %s\nMetadata saved: %s", final_output, meta_file)

        # 6) Optional upload
        if do_upload:
            # Check client secrets
            if not os.path.exists(CLIENT_SECRETS_FILE):
                raise RuntimeError(f"You asked to upload, but client secrets file not found: {CLIENT_SECRETS_FILE}")
            yt_title = f"{topic} — quick tip"
            yt_desc = desc + "\nAutomatically generated by pipeline."
            video_id = upload_to_youtube(final_output, yt_title, yt_desc, tags=[topic, "shorts", "automation"])
            logger.info("Uploaded video id: %s", video_id)

        return {"output": str(final_output), "meta": str(meta_file)}
    finally:
        # keep tmp files for debugging by default; remove if you prefer.
        logger.info("Temporary working dir: %s (not removed)", tmpdir)
        # if you want to remove temp dir, uncomment:
        # shutil.rmtree(tmpdir, ignore_errors=True)


